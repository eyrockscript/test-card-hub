/**
 * Renders a Playwright spec from checkout scenarios. Pure string building: every
 * value is embedded with JSON.stringify, so data can never break out of a literal.
 *
 * @typedef {{ name: string, outcome: string, cardNumber: string, expiry: string, cvv: string,
 *   cardholderName?: string, email?: string, postalCode?: string, note?: string }} Scenario
 */

const lit = (value) => JSON.stringify(value);
/** Header metadata goes into // comments: keep it on one line. */
const oneLine = (value) => String(value).replace(/[\r\n\u2028\u2029]+/g, ' ');

function scenarioLiteral(s) {
  const fields = [
    ['name', s.name], ['outcome', s.outcome], ['cardNumber', s.cardNumber], ['expiry', s.expiry], ['cvv', s.cvv],
    ['cardholderName', s.cardholderName], ['email', s.email], ['postalCode', s.postalCode], ['note', s.note],
  ].filter(([, v]) => v !== undefined && v !== null && v !== '');
  return `  { ${fields.map(([k, v]) => `${k}: ${lit(v)}`).join(', ')} },`;
}

const HELPERS = `// TODO: map these helpers to YOUR checkout. The selectors below are a starting point.
// If the gateway renders card fields inside an iframe (Stripe Elements, hosted fields),
// use page.frameLocator('<iframe selector>') to reach them.
async function fillCheckout(page: Page, s: Scenario) {
  if (s.email) await page.getByLabel(/correo|e-?mail/i).fill(s.email);
  if (s.cardholderName) await page.getByLabel(/titular|nombre en la tarjeta|cardholder|name on card/i).fill(s.cardholderName);
  await page.getByLabel(/n[uú]mero de (la )?tarjeta|card number/i).fill(s.cardNumber);
  await page.getByLabel(/vencimiento|expiraci[oó]n|expiry|expiration/i).fill(s.expiry);
  await page.getByLabel(/cvv|cvc|c[oó]digo de seguridad|security code/i).fill(s.cvv);
  if (s.postalCode) await page.getByLabel(/c[oó]digo postal|postal|zip/i).fill(s.postalCode);
  await page.getByRole('button', { name: /pagar|pay|confirmar|confirm/i }).click();
}

async function expectOutcome(page: Page, outcome: Scenario['outcome']) {
  const messages: Record<Scenario['outcome'], RegExp> = {
    approved: /aprobad|gracias|confirmad|approved|thank you|success/i,
    declined: /rechazad|declinad|declined|denied|no pudimos/i,
    insufficient: /fondos insuficientes|insufficient funds/i,
    review: /3d ?secure|autentica|authenticat|verifica/i,
    other: /error|inv[aá]lid|invalid/i,
  };
  await expect(page.getByText(messages[outcome]).first()).toBeVisible({ timeout: 30_000 });
}`;

/**
 * @param {{ gatewayName: string, docsUrl: string, verifiedAt: string, checkoutUrl: string,
 *   version: string, scenarios: Scenario[] }} input
 * @returns {string}
 */
export function renderPlaywrightSpec(input) {
  const header = [
    `// Generated by test-card-hub-mcp ${input.version}. Sandbox only: never run against production keys.`,
    `// Cards: ${oneLine(input.gatewayName)} official docs, verified ${oneLine(input.verifiedAt)}.`,
    `// Source: ${oneLine(input.docsUrl)}`,
    '// Field values follow the gateway docs where they set a rule; the rest (postal code, and any',
    '// field whose fieldSources is any_value / any_future_date in find_test_cards) are generic values.',
    "import { test, expect, type Page } from '@playwright/test';",
    '',
    `const CHECKOUT_URL = process.env.CHECKOUT_URL ?? ${lit(input.checkoutUrl)};`,
    '',
    'type Scenario = {',
    "  name: string; outcome: 'approved' | 'declined' | 'insufficient' | 'review' | 'other';",
    '  cardNumber: string; expiry: string; cvv: string;',
    '  cardholderName?: string; email?: string; postalCode?: string; note?: string;',
    '};',
    '',
    'const scenarios: Scenario[] = [',
    ...input.scenarios.map(scenarioLiteral),
    '];',
    '',
    HELPERS,
    '',
    `test.describe(${lit(`${input.gatewayName} checkout (sandbox)`)}, () => {`,
    '  scenarios.forEach((s, i) => {',
    '    test(`${i + 1}. ${s.name}`, async ({ page }) => {',
    '      await page.goto(CHECKOUT_URL);',
    '      await fillCheckout(page, s);',
    '      await expectOutcome(page, s.outcome);',
    '    });',
    '  });',
    '});',
    '',
  ];
  return header.join('\n');
}
